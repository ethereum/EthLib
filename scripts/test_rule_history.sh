#!/usr/bin/env bash
# The rule history must write exactly the lines that scripts/RuleHistoryTest
# plants, pass its own file, and fail on a changed, missing or extra line, a
# missing file, a scan that finds no rule, a missing fork type and an unknown
# argument.
# Run from anywhere.
set -uo pipefail
cd "$(dirname "$0")/.."
FAIL=0
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if ! lake build --wfail RuleHistoryTest rule-history >"$WORK/build" 2>&1; then
  echo "FAIL: the fixtures or the tool do not build"; cat "$WORK/build"; exit 1
fi

history() {
  lake exe rule-history --module RuleHistoryTest --scope RuleHistoryTest.Rules \
    --base RuleHistoryTest.Base "$@" 2>"$WORK/err"
}

# The doc comment of each fixture says why it has these lines.
TAB=$'\t'
sed "s/ | /$TAB/g" >"$WORK/expected" <<'END'
# Generated by `lake exe rule-history` from compiled code. Do not edit by hand.
# Each line is a rule, a fork (- for a constant) and the value that the code computes.
# A pull request that changes a line names the source that requires the new value.
RuleHistoryTest.Rules.access · false | early | 800
RuleHistoryTest.Rules.access · false | middle | 2100
RuleHistoryTest.Rules.access · false | late | 2100
RuleHistoryTest.Rules.access · true | early | 100
RuleHistoryTest.Rules.access · true | middle | 100
RuleHistoryTest.Rules.access · true | late | 100
(RuleHistoryTest.Rules.blobs · _).base | early | none
(RuleHistoryTest.Rules.blobs · _).base | middle | some 6
(RuleHistoryTest.Rules.blobs · _).base | late | some 9
(RuleHistoryTest.Rules.blobs · _).refund | early | none
(RuleHistoryTest.Rules.blobs · _).refund | middle | some 0
(RuleHistoryTest.Rules.blobs · _).refund | late | some 1
RuleHistoryTest.Rules.cost · | early | 50
RuleHistoryTest.Rules.cost · | middle | 200
RuleHistoryTest.Rules.cost · | late | 200
RuleHistoryTest.Rules.limit | - | 24576
(RuleHistoryTest.Rules.schedule ·).base | early | 21000
(RuleHistoryTest.Rules.schedule ·).base | middle | 21000
(RuleHistoryTest.Rules.schedule ·).base | late | 21000
(RuleHistoryTest.Rules.schedule ·).refund | early | 15000
(RuleHistoryTest.Rules.schedule ·).refund | middle | 4800
(RuleHistoryTest.Rules.schedule ·).refund | late | 4800
RuleHistoryTest.Rules.target · | early | none
RuleHistoryTest.Rules.target · | middle | none
RuleHistoryTest.Rules.target · | late | some 6
END

if history --file "$WORK/found" >"$WORK/out" && diff -u "$WORK/expected" "$WORK/found"; then
  echo "ok:   every planted rule is written at every fork, and nothing else"
else
  echo "FAIL: the lines differ from the planted ones"; cat "$WORK/out" "$WORK/err"; FAIL=1
fi

if history --check --file "$WORK/expected" >"$WORK/out"; then
  echo "ok:   the file that the code computes passes"
else
  echo "FAIL: the file that the code computes does not pass"; cat "$WORK/out" "$WORK/err"; FAIL=1
fi

# Each case edits the exact file once, and names the line that the check must print.
# A difference exits with 1, and any other code is a crash, not a detection.
expect_fail() {
  local what=$1 line=$2 got
  history --check --file "$WORK/case" >"$WORK/out"; got=$?
  if [ "$got" -eq 1 ] && grep -qxF -- "$line" "$WORK/out"; then
    echo "ok:   $what fails the check"
  else
    echo "FAIL: $what is not reported with exit 1 (exit $got)"; cat "$WORK/out" "$WORK/err"; FAIL=1
  fi
}

sed "s/^RuleHistoryTest.Rules.cost ·${TAB}middle${TAB}200\$/RuleHistoryTest.Rules.cost ·${TAB}middle${TAB}150/" \
  "$WORK/expected" >"$WORK/case"
expect_fail "a value that changed at an earlier fork" "+ RuleHistoryTest.Rules.cost ·${TAB}middle${TAB}200"

grep -vxF "RuleHistoryTest.Rules.limit${TAB}-${TAB}24576" "$WORK/expected" >"$WORK/case"
expect_fail "a line missing from the file" "+ RuleHistoryTest.Rules.limit${TAB}-${TAB}24576"

{ cat "$WORK/expected"; echo "RuleHistoryTest.Rules.gone${TAB}-${TAB}1"; } >"$WORK/case"
expect_fail "a line of a rule that no longer exists" "- RuleHistoryTest.Rules.gone${TAB}-${TAB}1"

history --check --file "$WORK/missing" >"$WORK/out"; got=$?
if [ "$got" -eq 1 ] && grep -qxF -- "+ RuleHistoryTest.Rules.limit${TAB}-${TAB}24576" "$WORK/out"; then
  echo "ok:   a missing file fails the check"
else
  echo "FAIL: exit $got on a missing file, expected 1"; cat "$WORK/out" "$WORK/err"; FAIL=1
fi

# A scope with no rule, or a namespace with no fork type, must not pass as an empty file.
expect_exit() {
  local what=$1 code=$2 message=$3 got
  shift 3
  lake exe rule-history "$@" >"$WORK/out" 2>"$WORK/err"; got=$?
  if [ "$got" -eq "$code" ] && grep -qxF -- "$message" "$WORK/err"; then
    echo "ok:   $what exits with $code"
  else
    echo "FAIL: exit $got on $what, expected $code"; cat "$WORK/out" "$WORK/err"; FAIL=1
  fi
}

expect_exit "a scan that finds no rule" 3 \
  "rule-history: no rule under [RuleHistoryTest.Other.Nothing] in the loaded modules" \
  --module RuleHistoryTest --scope RuleHistoryTest.Other.Nothing --base RuleHistoryTest.Base \
  --check --file "$WORK/expected"

expect_exit "a namespace with no fork type" 3 \
  "rule-history: no inductive type RuleHistoryTest.Rules.Fork in the loaded modules" \
  --module RuleHistoryTest --scope RuleHistoryTest.Rules --base RuleHistoryTest.Rules \
  --check --file "$WORK/expected"

expect_exit "an unknown argument" 2 "unknown argument --chek" --chek

exit "$FAIL"
