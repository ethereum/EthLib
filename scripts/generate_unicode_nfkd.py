"""Generate Unicode 16.0.0 compatibility decompositions and combining classes for Lean."""

import argparse
import hashlib
from functools import cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests/cryptography/keystore/unicode/UnicodeData.txt"
TARGET = ROOT / "EthLib/Base/Unicode/Data.lean"
DIGEST = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"


def generate() -> str:
    """Expand the pinned decomposition mappings, preserving their order."""
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != DIGEST:
        raise ValueError("UnicodeData.txt differs from the pinned Unicode 16.0.0 file")
    mappings = {}
    classes = {}
    for line in data.decode().splitlines():
        fields = line.split(";")
        code = int(fields[0], 16)
        rank = int(fields[3])
        if rank:
            classes[code] = rank
        parts = fields[5].split()
        if parts and parts[0].startswith("<"):
            parts = parts[1:]
        if parts:
            mappings[code] = tuple(int(part, 16) for part in parts)

    @cache
    def expand(code: int) -> tuple[int, ...]:
        # Unicode 16.0.0, Section 3.12.2: algorithmic full Hangul decomposition.
        if 0xAC00 <= code < 0xAC00 + 11172:
            index = code - 0xAC00
            result = (0x1100 + index // 588, 0x1161 + index % 588 // 28)
            return result + ((0x11A7 + index % 28,) if index % 28 else ())
        if code not in mappings:
            return (code,)
        return tuple(part for target in mappings[code] for part in expand(target))

    def scalar(code: int) -> bool:
        return 0 <= code <= 0x10FFFF and not 0xD800 <= code <= 0xDFFF

    expanded = [(code, expand(code)) for code in sorted(mappings)]
    assert all(scalar(code) and all(map(scalar, parts)) for code, parts in expanded)
    header = """module

/-!
# Unicode 16.0.0 normalization data

Generated by `scripts/generate_unicode_nfkd.py` from the pinned `UnicodeData.txt`.

The tables derive from Unicode, Inc. data.

The Unicode License V3 is in `EthLib/Base/Unicode/LICENSE`.

Copyright © 2024 Unicode, Inc.

The decomposition table recursively expands both canonical and compatibility mappings.

Hangul syllables are decomposed by the algorithm in `Unicode.lean`.

Source: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
-/

@[expose] public section

namespace EthLib.Base.Unicode.Data
"""
    lines = [header]

    def table(name: str, type_: str, rows: list[str]) -> None:
        chunks = [rows[i : i + 64] for i in range(0, len(rows), 64)]
        for i, chunk in enumerate(chunks):
            lines.extend(
                [
                    f"\n/-- Part {i + 1} of the {name} table. -/\n"
                    f"def {name}{i} : Array {type_} := #[",
                    ",\n".join(chunk),
                    "]\n",
                ]
            )
        lines.append(f"\n/-- The {name} table, sorted by code point. -/")
        lines.append(f"def {name} : Array {type_} :=")
        lines.append("\n    ++ ".join("  " + name + str(i) for i in range(len(chunks))))
        lines.append("\n")

    table(
        "decompositions",
        "(Nat × List Nat)",
        [
            f"  (0x{code:X}, [{', '.join(f'0x{part:X}' for part in parts)}])"
            if len(parts) < 12
            else f"  (0x{code:X}, [\n    {', '.join(f'0x{part:X}' for part in parts[:9])},\n"
            f"    {', '.join(f'0x{part:X}' for part in parts[9:])}])"
            for code, parts in expanded
        ],
    )
    table(
        "combiningClasses",
        "(Nat × Nat)",
        [f"  (0x{code:X}, {rank})" for code, rank in sorted(classes.items())],
    )
    lines.append("\nend EthLib.Base.Unicode.Data\n")
    return "\n".join(lines)


def main() -> None:
    """Write the table, or check that the committed table is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit("Unicode normalization table is stale")
    else:
        TARGET.write_text(expected)


if __name__ == "__main__":
    main()
